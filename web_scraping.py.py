# Function to standardize orders datasets
def standardize_orders(df):

    # Clean text columns
    text_columns = [
        "Order_ID",
        "Customer_ID",
        "Product_ID",
        "Order_Status",
        "Payment_Method"
    ]

    for col in text_columns:
        df[col] = df[col].apply(
            lambda x: x.strip() if isinstance(x, str) else x
        )

    # Standardize text capitalization
    df["Order_Status"] = df["Order_Status"].str.title()
    df["Payment_Method"] = df["Payment_Method"].str.title()

    # Convert Quantity to numeric
    df["Quantity"] = pd.to_numeric(
        df["Quantity"].astype(str)
        .str.replace("pcs", "", regex=False)
        .str.strip(),
        errors="coerce"
    )

    # Convert Discount to decimal
    discount = df["Discount"].astype(str).str.strip()

    has_percent = discount.str.contains("%", na=False)

    discount = discount.str.replace("%", "", regex=False)

    discount = pd.to_numeric(discount, errors="coerce")

    discount.loc[has_percent] = discount.loc[has_percent] / 100

    df["Discount"] = discount

    # Convert numerical columns
    numeric_columns = [
        "Unit_Price",
        "Shipping_Cost"
    ]

    for col in numeric_columns:
        df[col] = pd.to_numeric(
            df[col], errors="coerce"
        )

    # Convert dates
    df["Order_Date"] = pd.to_datetime(
        df["Order_Date"], errors="coerce"
    )

    df["Ship_Date"] = pd.to_datetime(
        df["Ship_Date"], errors="coerce"
    )

    return df


