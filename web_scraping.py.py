def inspect_orders(df, name):

    print("\n" + "=" * 55)
    print(f"DATA QUALITY REPORT: {name}")
    print("=" * 55)

    print("Dataset Shape:", df.shape)

    # 1. Missing Values
    print("\n1. Missing Values:")
    print(df.isnull().sum())

    # 2. Duplicate Records
    print("\n2. Exact Duplicate Rows:")
    print(df.duplicated().sum())

    # 3. Quantity Validation
    quantity = pd.to_numeric(
        df["Quantity"].astype(str).str.replace(
            " pcs", "", regex=False
        ),
        errors="coerce"
    )

    print("\n3. Invalid Quantity:")
    print((quantity <= 0).sum())

    # 4. Discount Validation
    discount = pd.to_numeric(
        df["Discount"].astype(str).str.replace(
            "%", "", regex=False
        ),
        errors="coerce"
    )

    discount.loc[
        df["Discount"].astype(str).str.contains(
            "%", na=False
        )
    ] = discount.loc[
        df["Discount"].astype(str).str.contains(
            "%", na=False
        )
    ] / 100

    print("\n4. Invalid Discount:")
    print(((discount < 0) | (discount > 1)).sum())

    # 5. Date Validation
    order_dates = pd.to_datetime(
        df["Order_Date"], errors="coerce"
    )

    ship_dates = pd.to_datetime(
        df["Ship_Date"], errors="coerce"
    )

    print("\n5. Invalid Order Dates:")
    print(order_dates.isna().sum())

    print("\n6. Ship Date Before Order Date:")
    print(
        (
            ship_dates.notna()
            & order_dates.notna()
            & (ship_dates < order_dates)
        ).sum()
    )

    # 6. Customer ID Validation
    invalid_customers = (
        ~df["Customer_ID"].isin(
            customers_clean["Customer_ID"]
        )
        & df["Customer_ID"].notna()
    )

    print("\n7. Invalid Customer IDs:")
    print(invalid_customers.sum())

